-- FoodHub schema for PostgreSQL (Supabase). Paste into the Supabase SQL editor, or run `npm run db:setup`.
-- Re-running is safe: tables are only created if missing. Nothing here drops data.
-- No schema name is written, so it builds in whatever the search_path points at
-- (`public` on Supabase; a throwaway `foodhub_test` schema in the tests).

-- Members and admins
CREATE TABLE IF NOT EXISTS users (
  user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR(100) NOT NULL,
  email         VARCHAR(150) NOT NULL,
  phone         VARCHAR(20),
  address       VARCHAR(255),
  password_hash VARCHAR(255) NOT NULL,
  role          TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_users_email UNIQUE (email)
);

-- The dishes. Hide with is_available = false instead of deleting.
CREATE TABLE IF NOT EXISTS menu_items (
  item_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(100) NOT NULL,
  category     TEXT NOT NULL CHECK (category IN ('Mains', 'Sides', 'Drinks', 'Desserts')),
  description  TEXT,
  price        NUMERIC(6,2) NOT NULL,
  image        VARCHAR(255),
  is_available BOOLEAN NOT NULL DEFAULT TRUE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_menu_category ON menu_items (category, is_available);

-- One row per checkout
CREATE TABLE IF NOT EXISTS orders (
  order_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          INTEGER NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  order_date       TIMESTAMPTZ NOT NULL DEFAULT now(),
  delivery_address VARCHAR(255) NOT NULL,
  contact_phone    VARCHAR(20) NOT NULL,
  payment_method   TEXT NOT NULL DEFAULT 'cash' CHECK (payment_method IN ('cash', 'card', 'paynow')),
  notes            VARCHAR(255),
  status           TEXT NOT NULL DEFAULT 'Pending'
                   CHECK (status IN ('Pending', 'Preparing', 'Out for delivery', 'Delivered', 'Cancelled')),
  total_amount     NUMERIC(8,2) NOT NULL,
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_orders_user ON orders (user_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders (status);

-- MySQL's ON UPDATE CURRENT_TIMESTAMP, as a trigger
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_orders_updated_at ON orders;
CREATE TRIGGER trg_orders_updated_at BEFORE UPDATE ON orders
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Lines of each order. unit_price is copied at checkout so later price changes
-- do not alter past orders.
CREATE TABLE IF NOT EXISTS order_items (
  order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      INTEGER NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE ON UPDATE CASCADE,
  item_id       INTEGER NOT NULL REFERENCES menu_items (item_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  quantity      INTEGER NOT NULL CHECK (quantity > 0),
  unit_price    NUMERIC(6,2) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items (order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_item ON order_items (item_id);

-- Supabase exposes every table in `public` through its REST API with the public anon key.
-- Row Level Security with no policies shuts that door (password hashes live here).
-- The Express API connects as the database owner, which bypasses RLS, so it is unaffected.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE menu_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_items ENABLE ROW LEVEL SECURITY;
